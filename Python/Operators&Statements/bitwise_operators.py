print("========== Bitwise Operators ==========\n")

a = 5
b = 3

print("Value of a :", a)
print("Binary of a:", bin(a))

print("\nValue of b :", b)
print("Binary of b:", bin(b))

print("\n========== Bitwise AND (&) ==========")
print("a & b      :", a & b)
print("Binary     :", bin(a & b))

print("\n========== Bitwise OR (|) ==========")
print("a | b      :", a | b)
print("Binary     :", bin(a | b))

print("\n========== Bitwise XOR (^) ==========")
print("a ^ b      :", a ^ b)
print("Binary     :", bin(a ^ b))

print("\n========== Bitwise NOT (~) ==========")
print("~a         :", ~a)
print("~b         :", ~b)

print("\n========== Left Shift (<<) ==========")
print("a << 1     :", a << 1)
print("Binary     :", bin(a << 1))

print("a << 2     :", a << 2)
print("Binary     :", bin(a << 2))

print("\n========== Right Shift (>>) ==========")
print("a >> 1     :", a >> 1)
print("Binary     :", bin(a >> 1))

print("a >> 2     :", a >> 2)
print("Binary     :", bin(a >> 2))